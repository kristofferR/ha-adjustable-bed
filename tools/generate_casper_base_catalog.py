"""Generate durable Casper Base specifications from its accepted package-local catalog.

Usage: uv run --no-project python tools/generate_casper_base_catalog.py <report>
The input remains machine-local. Generated specifications contain no decompiled code.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

report = Path(sys.argv[1])
catalog = json.loads((report / "catalog.json").read_text())
items = list(catalog["items"].values())
indices = {item["id"]: index for index, item in enumerate(items)}
lines = [
    '"""Casper Base 1.0.8 package-local action and product specifications (row101).',
    "",
    "Generated by tools/generate_casper_base_catalog.py. Conditional restored",
    "products are explicit choices, never inferred from an advertisement.",
    '"""',
    "from typing import Final",
    "",
    "# name, short opcode, optional program opcode",
    "ACTIONS: Final = (",
]
for item in items:
    lines.append(
        f"    {(item['name'].removeprefix('deviceFunctionItem'), item['short'], item['long'] or None)!r},"
    )
lines += [
    ")",
    "",
    "# label, motor/massage/preset/clock/fan action indices, light/RGB/music/sleep/repeat/side",
    "PRODUCTS: Final = {",
]
for p in catalog["products"]:
    f = p["fields"]
    if not any(f.get(k) for k in ("24", "28", "2c", "30", "34")):
        continue
    key = p["name"].removeprefix("product").lower()
    groups = tuple(tuple(indices[i] for i in f.get(k, ())) for k in ("24", "28", "30", "34", "2c"))
    flags = tuple(bool(f.get(k)) for k in ("38", "3c", "40", "44", "48", "4c"))
    lines.append(f"    {key!r}: {(f['14'], *groups, *flags)!r},")
lines += ["}", ""]
Path("custom_components/adjustable_bed/casper_base_catalog.py").write_text("\n".join(lines))
