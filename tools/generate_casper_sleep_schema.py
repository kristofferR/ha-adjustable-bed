"""Generate the accepted row101 typed BLE response field specifications."""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

NAMES = dict(
    zip(
        ["53d8d8", "53d558", "53d7dc", "53d280", "53d48c", "53eaf4", "53fd00", "53fe78", "53fff0", "540300", "540478", "540788", "540a1c", "540c74", "540f50", "5411f8", "541400", "541584", "53da70", "53dd08", "534bac", "5349fc", "5358a0", "5355f0", "53518c", "534e50", "5350c0", "539e20", "53927c", "53905c", "538e3c", "538c64", "538898", "536d9c", "539bb4", "539a2c", "5398a4", "53971c", "5395dc", "539454", "53b664", "535ff0", "53629c"],
        ["mm_part", "mm_live", "mm_live_val", "mm_report", "mm_size", "mm_day", "mm_rem", "mm_light", "mm_heart", "mm_deep", "mm_breath", "mm_awake", "mm_sporadic", "mm_timestamp", "mm_status", "mm_revolve", "mm_move", "mm_month", "mm_time", "mm_time_val", "sxb_init_val", "sxb_init", "sxb_part", "sxb_live_val", "sxb_live", "sxb_report", "sxb_size", "sxb_status", "sxb_move", "sxb_snore", "sxb_heart", "sxb_breath", "sxb_sporadic", "sxb_day", "sxb_awake", "sxb_deep", "sxb_light", "sxb_rem", "sxb_outbed", "sxb_microawake", "sxb_month", "sxb_time", "sxb_time_val"],
        strict=True,
    )
)
LISTS = {
    "body_move": "mm_move",
    "body_revolve": "mm_revolve",
    "sleep_data": "mm_status",
    "snore": "mm_timestamp",
    "snore_count": "mm_timestamp",
    "sporadicsleep": "mm_sporadic",
}
source = (Path(sys.argv[1]) / "bean-fields.json").read_bytes()
entries = json.loads(source)
schemas = {}
for e in entries:
    address = e["function"]["address"][2:]
    if address not in NAMES:
        continue
    name = NAMES[address]
    fields = {}
    for f in e["fields"]:
        key = f["key"]
        types = f["types"]
        calls = f["calls"]
        kind = "dynamic"
        child = ""
        if types:
            typ = types[-1]
            kind = {
                "String": "str",
                "String?": "str?",
                "int?": "int?",
                "num": "num",
                "num?": "num?",
                "List?": "list?",
                "List<num>?": "nums",
                "Map<String, dynamic>": "map",
            }[typ]
        if calls:
            child = NAMES[calls[0][0][2:]]
            kind = "object"
        if "-0x1000" in f["gdt"] and kind.startswith("num"):
            kind = kind.replace("num", "to_int")
        if "-0xffd" in f["gdt"] and kind.startswith("num"):
            kind = kind.replace("num", "to_float")
        if name in ("mm_day", "mm_month") and kind == "object":
            kind = "object?"
        if name == "mm_day" and kind == "list?":
            child = LISTS[key]
        if name in ("mm_heart", "mm_breath") and kind == "list?":
            kind = "ints?"
        if name in ("sxb_day", "sxb_month") and child:
            kind = "object?"
        if name == "sxb_day" and key == "sleep_data":
            kind = "list_objects?"
            child = "sxb_status"
        if kind != "dynamic" or key not in fields:
            fields[key] = (kind, child)
    if name == "sxb_live":
        fields["val"] = ("object?", "sxb_live_val")
    schemas[name] = fields
Path("custom_components/adjustable_bed/casper_sleep_schema.py").write_text(
    '"""Row101 package-local typed response fields.\n\n'
    "Generated by tools/generate_casper_sleep_schema.py; do not edit by hand.\n"
    f"Input SHA-256: bean-fields.json {hashlib.sha256(source).hexdigest()}.\n"
    '"""\nfrom typing import Final\n\nSCHEMAS: Final[dict[str, dict[str, tuple[str, str]]]] = '
    + repr(schemas)
    + "\n"
)
