NOTICE = (
    "<!-- Generated by scripts/generate_codec_docs.py from the codec and profile data. "
    "Edit those, not this block. -->"
)


def _table(header: tuple[str, ...], rows: Iterable[tuple[str, ...]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    return lines


def _block(*parts: str | list[str]) -> str:
    """Join paragraphs and tables, separated by blank lines, under the notice."""
    lines = [NOTICE]
    for part in parts:
        if isinstance(part, str):
            part = [part] if part.startswith("#") else _wrap(part)
        lines += ["", *part]
    return "\n".join(lines)


def _wrap(paragraph: str) -> list[str]:
    """Wrap prose like the hand-written text, never inside a code span."""
    protected = re.sub(r"`[^`]*`", lambda span: span[0].replace(" ", "\0"), paragraph)
    return [
        line.replace("\0", " ") for line in textwrap.wrap(protected, 82, break_on_hyphens=False)
    ]


def _hex(data: bytes) -> str:
    return f"`{data.hex(' ').upper()}`"


