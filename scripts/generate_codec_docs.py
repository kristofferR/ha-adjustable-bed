"""Regenerate the tables in codec guides that profile data already knows.

A codec guide marks each generated region with ``<!-- generated:<name> -->`` and
``<!-- /generated -->``. Run this script to rewrite the regions, or with
``--check`` to fail when one is stale (``tests/test_codec_docs.py`` does).

To generate a block for another family, write a renderer over its profile module
and add it to ``BLOCKS``.

    uv run --no-sync python scripts/generate_codec_docs.py [--check]
"""

from __future__ import annotations

import re
import sys
from collections.abc import Callable, Iterable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from custom_components.adjustable_bed.codec import jiecang as jiecang_codec  # noqa: E402
from custom_components.adjustable_bed.const import (  # noqa: E402
    BED_TYPE_COMFORT_MOTION,
    BED_TYPE_JIECANG,
    BED_TYPE_JIECANG_APP,
    JIECANG_APP_LAYOUTS,
    JIECANG_APP_PROFILES,
)
from custom_components.adjustable_bed.profiles import jiecang as jiecang_profiles  # noqa: E402

NOTICE = (
    "<!-- Generated by scripts/generate_codec_docs.py from the profile data. "
    "Edit the profile, not this block. -->"
)
_FRAME_NAMES = {
    jiecang_codec.SHORT_RELEASE: "short release",
    jiecang_codec.LONG_RELEASE: "long release",
}


def _table(header: tuple[str, ...], rows: Iterable[tuple[str, ...]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    return lines


def _frame(command: bytes) -> str:
    return _FRAME_NAMES.get(command) or f"`{command.hex().upper()}`"


def _schedule(schedule: jiecang_profiles.Schedule) -> str:
    return ", ".join(f"+{offset} ms {_frame(command)}" for offset, command in schedule) or "none"


def _tap(tap: jiecang_profiles.Tap) -> str:
    sends = f"{tap.repeats} × {tap.repeat_ms} ms" if tap.repeats > 1 else "once"
    if tap.release is None:
        return f"{sends}, no release"
    return f"{sends}, {_frame(tap.release)} after {tap.release_after_ms} ms"


def _massage(levels: tuple[int, ...]) -> str:
    span = f"0-{len(levels) - 1}"
    if levels == tuple(range(len(levels))):
        return f"{span} (wire equals level)"
    return f"{span} (wire {' '.join(f'{wire:02X}' for wire in levels)})"


def _profiles() -> dict[str, jiecang_profiles.JiecangProfile]:
    return {"legacy": jiecang_profiles.LEGACY, **jiecang_profiles.APP_PROFILES}


def _name(key: str) -> str:
    return "Legacy route" if key == "legacy" else JIECANG_APP_PROFILES[key]


def _bed_types(key: str) -> str:
    if key == "legacy":
        return f"`{BED_TYPE_JIECANG}`, `{BED_TYPE_COMFORT_MOTION}`"
    return f"`{BED_TYPE_JIECANG_APP}`"


def render_jiecang_profiles() -> str:
    profiles = _profiles()
    summary = _table(
        ("Profile", "Bed type", "Transports", "Memory", "Massage levels", "Name rule", "Startup"),
        (
            (
                _name(key),
                _bed_types(key),
                ", ".join(transport.upper() for transport in profile.transports),
                f"{profile.memory_slots} slots, payload `{profile.memory_payload.hex(' ').upper()}`",
                _massage(profile.massage_levels),
                f"`{profile.name_rule.pattern}`" if profile.name_rule else "none",
                f"{len(profile.bootstrap)} queries, last at +{profile.bootstrap[-1][0]} ms"
                if profile.bootstrap
                else "none",
            )
            for key, profile in profiles.items()
        ),
    )
    timing = _table(
        (
            "Profile",
            "Hold refresh",
            "Repeats",
            "Final frame",
            "Release after hold",
            "Explicit stop",
        ),
        (
            (
                _name(key),
                f"{profile.hold.repeat_ms} ms ({'fixed rate' if profile.fixed_rate else 'after each write'})",
                str(profile.hold.repeats or "motor pulse count"),
                "yes" if profile.hold.final_frame else "no",
                _schedule(profile.hold.releases),
                _schedule(
                    tuple(
                        (offset - profile.hold.releases[0][0], command)
                        for offset, command in profile.hold.releases
                    )
                ),
            )
            for key, profile in profiles.items()
        ),
    )
    actions = _table(
        ("Profile", "Presets and memory recall", "Memory save"),
        (
            (_name(key), _tap(profile.recall), _tap(profile.memory_save))
            for key, profile in profiles.items()
        ),
    )
    layouts: dict[tuple[str, tuple[str, ...]], list[str]] = {}
    for key, profile in profiles.items():
        for layout, axes in profile.layouts.items():
            layouts.setdefault((layout, axes), []).append(_name(key))
    layout_table = _table(
        ("Layout", "Axes", "Massage zones", "Profiles"),
        (
            (
                f"`{layout}` ({JIECANG_APP_LAYOUTS[layout]})",
                ", ".join(axes),
                ", ".join(jiecang_profiles.massage_zones(layout)),
                ", ".join(names),
            )
            for (layout, axes), names in sorted(
                layouts.items(), key=lambda item: list(JIECANG_APP_LAYOUTS).index(item[0][0])
            )
        ),
    )
    layoutless = ", ".join(_name(key) for key, profile in profiles.items() if not profile.layouts)
    sections = (
        ("Profile summary", summary),
        ("Hold and release timing", timing),
        ("One-shot timing", actions),
        ("Layouts and axes", layout_table),
    )
    lines = [NOTICE]
    for title, table in sections:
        lines += ["", f"**{title}**", "", *table]
    lines += ["", f"{layoutless} has no selectable layouts: it uses the entry's motor count."]
    return "\n".join(lines)


# (guide, block name) -> renderer
BLOCKS: dict[tuple[str, str], Callable[[], str]] = {
    ("docs/beds/jiecang.md", "jiecang-profiles"): render_jiecang_profiles,
}


def _pattern(name: str) -> re.Pattern[str]:
    return re.compile(
        rf"(<!-- generated:{re.escape(name)} -->\n).*?(<!-- /generated -->)", re.DOTALL
    )


def render(text: str, name: str, body: str) -> str:
    pattern = _pattern(name)
    if not pattern.search(text):
        raise ValueError(f"missing generated block {name!r}")
    return pattern.sub(lambda match: f"{match[1]}{body}\n{match[2]}", text, count=1)


def stale_guides() -> list[str]:
    """Return the guides whose generated blocks differ from their profile data."""
    stale: list[str] = []
    for (guide, name), renderer in BLOCKS.items():
        path = ROOT / guide
        text = path.read_text(encoding="utf-8")
        if render(text, name, renderer()) != text:
            stale.append(guide)
    return stale


def main(argv: list[str]) -> int:
    if "--check" in argv:
        stale = stale_guides()
        for guide in stale:
            print(f"{guide} is stale; run scripts/generate_codec_docs.py", file=sys.stderr)
        return 1 if stale else 0
    for (guide, name), renderer in BLOCKS.items():
        path = ROOT / guide
        path.write_text(
            render(path.read_text(encoding="utf-8"), name, renderer()), encoding="utf-8"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
