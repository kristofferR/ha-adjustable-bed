REVERIE_MODEL_CHOICES: Final[dict[str, str]] = {
    "Other": "Other",
    **{model_id: model_id for model_id in REVERIE_MODEL_PROFILES if model_id != "Other"},
}

REVERIE_MODEL_FALLBACK: Final = "Other"


def resolve_reverie_model(model_id: str | None) -> ReverieModelProfile:
    """Resolve an exact model ID, using the app's explicit Other fallback."""
    return REVERIE_MODEL_PROFILES.get(
        model_id or REVERIE_MODEL_FALLBACK,
        REVERIE_MODEL_PROFILES[REVERIE_MODEL_FALLBACK],
    )
