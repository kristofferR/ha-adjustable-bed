def scan_matches(name: str | None) -> bool:
    return (
        name is not None
        and len(name.strip()) >= 4
        and (
            name.upper().startswith(SCAN_PREFIXES)
            or name[:4].upper() in (*LAYOUTS, *NON_CONTROL_LAYOUTS)
        )
    )


def layout_from_name(name: str) -> str | None:
    if not scan_matches(name):
        return None
    value = name.upper()
    selected = next(
        (
            ALIASES[value[:n]]
            for n in (9, 8, 7, 6, 5, 4)
            if len(value) >= n and value[:n] in ALIASES
        ),
        None,
    )
    if selected is None and len(value) == 10:
        selected = ALIASES.get(value)
    value = selected or value
    if "209A05" in value or value.strip()[:4] == "QRRM":
        return None
    layout = ALIASES.get(value.strip()[:4], value.strip()[:4])
    return layout if layout in LAYOUTS and layout not in NAVIGATION else None


def poll_interval(name: str | None, *, raw: bool) -> int:
    prefix = (name or "")[:4].upper()
    return 170 if raw and prefix == "6BRM" else 110 if prefix in ("TWRM", "MLRM") else 150


