@dataclass(frozen=True, slots=True)
class Axis:
    key: str
    label: str
    up: int
    down: int
    stop: int
    selector: str = "default"


@dataclass(frozen=True, slots=True)
class EasyCtrlProfile:
    key: int
    page: str
    axes: tuple[Axis, ...]
    stream: bool
    memory: int
    presets: tuple[str, ...]
    massage: bool
    light: bool
    rgb: bool
    alarm: bool
    flat_keep: bool
    flat_latched: bool
    refresh_ms: int = 100
    flat_threshold_ms: int = 400
    flat_tap_ms: int = 100  # HA finite tap duration, not an app minimum.
    keep_delay_ms: int = 50
    setting_delay_ms: int = 120
    alarm_delay_ms: int = 150
    query_delay_ms: int = 200
    release_ms: tuple[int, ...] = (0, 20, 40)

    @property
    def motor_count(self) -> int:
        # OrderUtil's individual m1..m4 members, excluding combined m13/m24
        # groups and repeated Left/Right/Both controls for the same channel.
        channels = {axis.up for axis in self.axes if axis.up in (0x101, 0x105, 0x109, 0x10D)}
        return len(channels) or 1

    @property
    def execution(self) -> ExecutionCapabilities:
        return ExecutionCapabilities(hold="stream" if self.stream else "latched")

    def axis(self, key: str) -> Axis:
        return next(axis for axis in self.axes if axis.key == key)


