def scan_matches(name: str | None) -> bool:
    if name is None or len(name.strip()) < 4:
        return False
    original = name.upper()
    return original.startswith(SCAN_PREFIXES) or original[:4] in LAYOUTS


def worker_interval(app: str, name: str | None, raw: bool) -> int:
    profile = APPS[app]
    return (
        profile.raw_6brm_poll_ms
        if raw and name is not None and name.strip().upper().startswith("6BRM")
        else profile.poll_ms
    )
