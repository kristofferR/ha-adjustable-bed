"""All accepted row176 literals and receive cases through production code.

Frozen fixtures are copied from the accepted report, never generated by the
codec or by executing the analyst's reproducer.
"""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path

import pytest

from custom_components.adjustable_bed.codec.okin_nframe import SideRecordParser
from custom_components.adjustable_bed.profiles import ultramatic as app

_PATH = Path(__file__).parent / "fixtures/ultramatic_smart_bed"
VECTORS = json.loads((_PATH / "vectors.json").read_text())
CORRECTION = json.loads((_PATH / "alarm_correction.json").read_text())["cases"]
SEND_CASES = VECTORS["commands"] + [
    row for row in CORRECTION if row["case_kind"] == "new_unequal_type_side"
]


@pytest.mark.parametrize("row", SEND_CASES, ids=lambda r: r["id"])
def test_frozen_sends(row):
    inputs = row["inputs"]
    if row["action"] == "clock":
        actual = app.clock(datetime.fromisoformat(inputs["local_time"]))
    elif row["action"] == "alarm":
        inputs = dict(inputs)
        if "now" in inputs:
            inputs["now"] = datetime.fromisoformat(inputs["now"])
        actual = app.alarm(**inputs)
        assert actual[3] == inputs["type_code"]
        assert actual[8] == app.SELECTORS[inputs["side"]]
    elif row["action"] == "query_massage":
        actual = app.QUERY_MASSAGE
    elif row["action"] == "query_alarm":
        actual = app.QUERY_ALARM
    else:
        actual = app.control(row["action"], **inputs)
    assert actual == bytes.fromhex(row["expected_bytes"])


@pytest.mark.parametrize("row", VECTORS["parsers"], ids=lambda r: r["id"])
def test_frozen_receive_cases(row):
    parser = SideRecordParser(app.HEADERS)
    inputs = row["inputs"]
    actual = None
    for chunk in row["packets"]:
        if inputs.get("connected", True):
            records = parser.feed(bytes.fromhex(chunk))
            if records is not None:
                actual = app.state(
                    records,
                    inputs.get("side", "AB"),
                    datetime.fromisoformat(inputs.get("now", "2026-11-17T08:41:00")),
                )
    # Intentional safe rejection of the source's recognized-short-frame crash.
    assert actual == row["expected_parsed"]


@pytest.mark.parametrize("row", VECTORS["timer_buckets"])
def test_frozen_timer_boundaries(row):
    assert app.timer_bucket(row["value"]) == row["expected"]


@pytest.mark.parametrize("row", VECTORS["ab_equivalence"])
def test_frozen_side_equivalence(row):
    assert app.equivalent(bytes(row["a"]), bytes(row["b"]), massage=True) == row["expected"]
